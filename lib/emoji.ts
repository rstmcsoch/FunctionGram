/** Flattened, de-duplicated list of every emoji the picker can insert. */
export const ALL_EMOJI: string[] = [...new Set(EMOJI_CATEGORIES.flatMap(category => category.emoji))];

/** Category ids in picker order, so the UI and the tests agree. */
export const EMOJI_CATEGORY_IDS: string[] = EMOJI_CATEGORIES.map(category => category.id);

/**
 * Case-insensitive substring search over the whole catalogue. Matching is done
 * on the emoji itself plus the category id, so "smile" and "😀" both work
 * without shipping a separate keyword table.
 */
export function searchEmoji(term: string): string[] {
  const needle = term.trim().toLowerCase();
  if (!needle) return ALL_EMOJI;
  const matches: string[] = [];
  for (const category of EMOJI_CATEGORIES) {
    if (category.id.includes(needle)) {
      matches.push(...category.emoji);
      continue;
    }
    matches.push(...category.emoji.filter(emoji => emoji.includes(needle)));
  }
  return [...new Set(matches)];
}

/**
 * Insert `emoji` into `value` at `cursor`, leaving the rest of the text intact.
 *
 * The composer must never replace what the user already typed: the emoji is
 * spliced in at the caret (or appended when the field has never been focused)
 * and the caret is moved past it.
 */
export function insertEmoji(value: string, emoji: string, cursor = value.length): { value: string; cursor: number } {
  const at = Math.max(0, Math.min(cursor, value.length));
  return { value: value.slice(0, at) + emoji + value.slice(at), cursor: at + emoji.length };
}
